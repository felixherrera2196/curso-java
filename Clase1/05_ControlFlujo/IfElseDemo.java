public class IfElseDemo {
    public static void main(String[] args) {
        int nota = 75;
        if (nota >= 90) {
            System.out.println("Excelente");
        } else if (nota >= 60) {
            System.out.println("Aprobado");
        } else {
            System.out.println("Reprobado");
        }
    }
}
