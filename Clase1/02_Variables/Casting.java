public class Casting {
    public static void main(String[] args) {
        double altura = 1.83;
        int alturaEntera = (int) altura;
        final double PI = 3.1416;
        System.out.println("Altura original: " + altura);
        System.out.println("Altura entera: " + alturaEntera);
        System.out.println("Constante PI: " + PI);
    }
}
